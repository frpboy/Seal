RECIPIENT_SHA256='033aa324ba76e6d67ef28a0f2d0dc336e00823b3e023d6b87129f283660b8cc3'
CIPHER_MAX=200*1024**2


def require(ok,why):
    if not ok: raise ValueError(why)


def module(name):
    spec=importlib.util.spec_from_file_location(name,Path(__file__).with_name(name+'.py'))
    m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m);return m


def exact_source(expected):
    require(re.fullmatch('[0-9a-f]{40}',expected) is not None,'full reviewed source SHA required')
    require(os.environ.get('GITHUB_REPOSITORY')=='frpboy/Seali' and os.environ.get('GITHUB_EVENT_NAME')=='workflow_dispatch','manual owner repo only')
    require(os.environ.get('REPOSITORY_PRIVATE')=='false','public standard runner only')
    actual=subprocess.check_output(['git','rev-parse','HEAD'],text=True).strip()
    require(actual==expected==os.environ.get('GITHUB_SHA'),'checkout/source SHA differs')


class LimitedWriter:
    def __init__(self,raw):
        self.raw=raw;self.count=0;self.started=time.monotonic()
    def write(self,data):
        self.count+=len(data)
        require(self.count<CIPHER_MAX-1024**2,'custody compression exceeds bound')
        require(time.monotonic()-self.started<180,'custody compression wall limit')
        return self.raw.write(data)
    def flush(self): return self.raw.flush()


def write_archive(archive,root,reduced):
    with archive.open('xb') as raw,tarfile.open(fileobj=LimitedWriter(raw),mode='w|gz') as t:
        names=['evidence','recipes','build','tmp','home'] if reduced else ['sources','evidence','recipes','build','tmp','home']
        for name in names:
            if (root/name).exists(): t.add(root/name,arcname=name)
        if not reduced:
            for name in ['openssl.tar.gz','expat.tar.xz']:
                if (root/'inputs'/name).exists(): t.add(root/'inputs'/name,arcname='inputs/'+name)


def custody(root,repo,summary):
    """Encrypted allowlist custody only; do not include NDK/env/secrets."""
    helper=module('bounded-process');recipient=repo/'recipient.pem'
    require(helper.sha(recipient)==RECIPIENT_SHA256,'recipient differs')
    (root/'evidence/outcome.json').write_text(json.dumps(summary,indent=2)+'\n')
    recipes=root/'recipes';shutil.copytree(repo,recipes)
    # Exclude generated bytecode; no private keys are ever copied into recipes.
    for p in list(recipes.rglob('__pycache__')): shutil.rmtree(p)
    for p in recipes.rglob('*'):
        require(not p.is_symlink(),'recipe symlinks rejected')
    rows=[]
    for name in ['sources','evidence','recipes','build','tmp','home']:
        if (root/name).exists():
            for row in helper.inventory(root/name):
                rows.append({**row,'path':name+'/'+row['path']})
    (root/'evidence/custody-inventory.json').write_text(json.dumps(rows,indent=2)+'\n')
    archive=root/'custody.tar.gz';cipher=root/'owned-components.cms'
    try:
        mode='complete'
        try:
            write_archive(archive,root,reduced=False)
        except ValueError:
            archive.unlink(missing_ok=True)
            mode='reduced-build-evidence'
            # One bounded packing fallback, never a source-build retry. Omit
            # refetchable inputs/trees; retain buildstage/configs/logs/evidence.
            write_archive(archive,root,reduced=True)
        require(archive.stat().st_size<CIPHER_MAX-1024**2,'custody compression exceeds bound')
        subprocess.run(['/usr/bin/timeout','--signal=TERM','--kill-after=10s','120','openssl','cms','-encrypt','-binary','-aes-256-cbc','-in',str(archive),
                        '-outform','DER','-out',str(cipher),str(recipient)],check=True,timeout=120,
                        stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
        require(cipher.stat().st_size<=CIPHER_MAX,'cipher bound exceeded')
        result={'cipher_bytes':cipher.stat().st_size,'cipher_sha256':helper.sha(cipher),'custody_mode':mode,
                'source_sha':summary['source_sha'],'status':summary['status'],
                'runtime_tested':False,'publication_ready':False,'output_pins_changed':False}
        (root/'custody-public.json').write_text(json.dumps(result,indent=2)+'\n')
        return result
    except BaseException:
        cipher.unlink(missing_ok=True)
        raise
    finally:
        archive.unlink(missing_ok=True)


def main():
    p=argparse.ArgumentParser();p.add_argument('--expected-source-sha',required=True);a=p.parse_args()
    exact_source(a.expected_source_sha)
    root=Path(os.environ['RUNNER_TEMP'])/'seali-owned-components-job'
    repo=Path(__file__).resolve().parent
    require(not root.exists(),'fresh root required')
    summary={'source_sha':a.expected_source_sha,'status':'STARTING','runtime_tested':False,
        'publication_ready':False,'output_pins_changed':False,'steps':[],
        'limits':'No hard RAM/cgroup/pid/filesystem sandbox. Sampled disk bounds, detached sessions can escape process-group cleanup. Source trees are checked before mutation, not immutable.'}
    helper=module('bounded-process');validation=module('input-validation')
    started=time.monotonic();failed=False
    # Downloads and prerequisite preparation run with no inherited token or
    # credential environment. Only public sources are contacted.
    env={'PATH':'/usr/bin:/bin','LANG':'C.UTF-8','LC_ALL':'C.UTF-8','PYTHONDONTWRITEBYTECODE':'1','PYTHONNOUSERSITE':'1'}
    try:
        prep=root.parent/'seali-owned-components-prepare.log'
        with prep.open('wb') as log:
            subprocess.run(['/usr/bin/timeout','--signal=TERM','--kill-after=30s','600',
                '/usr/bin/python3',str(repo/'prepare.py'),'--root',str(root)],env=env,stdout=log,stderr=subprocess.STDOUT,check=True,timeout=640)
        shutil.move(prep,root/'evidence/prepare.log')
        admission=json.loads((root/'evidence/prerequisites.json').read_text())
        # All source recipe/tool identities are retained before code runs.
        (root/'evidence/recipe-manifest.json').write_text(json.dumps(helper.inventory(repo),indent=2)+'\n')
        # root/home and root/tmp were already created by source preparer.
        env.update(HOME=str(root/'home'),TMPDIR=str(root/'tmp'),SOURCE_DATE_EPOCH='1794338241',
            ADMISSION_JSON=str(root/'evidence/prerequisites.json'),ANDROID_NDK_HOME=admission['ndk_root'],
            OPENSSL_SOURCE=admission['trees']['openssl'],EXPAT_SOURCE=admission['trees']['expat'],
            BUILD_ROOT=str(root/'build'),TARGET_ABI='arm64-v8a',CUSTODY_ROOT=str(root))
        # Fresh whole NDK check before build. Source tree check receipts were
        # generated immediately before this point; recipe applies disclosed patch.
        validation.verify_ndk(Path(admission['ndk_root']),root/'inputs/ndk.zip')
        command=admission['network']['command_prefix']+['bash',str(repo/'build-two-components.sh')]
        row=helper.bounded(command,env,root/'evidence/build.log',3600,root)
        row['name']='source-build';summary['steps'].append(row)
        require(row['exit_code']==0 and row['stop_reason'] is None,'source build stopped')
        # postbuild reads configs, symbols and runs host target preprocessor only.
        row=helper.bounded(admission['network']['command_prefix']+['/usr/bin/python3',str(repo/'postbuild.py')],
            env,root/'evidence/postbuild.log',300,root)
        row['name']='static-postbuild';summary['steps'].append(row)
        require(row['exit_code']==0 and row['stop_reason'] is None,'static postbuild stopped')
        summary['status']='SOURCE_COMPONENTS_BUILT_STATIC_ONLY_REVIEW_REQUIRED'
    except BaseException as error:
        failed=True;summary['status']='STOPPED_NO_RETRY';summary['failure_type']=type(error).__name__
        # Raw error text may contain paths/private content; keep only in ciphertext.
        summary['failure_detail']=str(error)
    finally:
        summary['seconds']=round(time.monotonic()-started,3)
        if root.exists():
            (root/'evidence').mkdir(exist_ok=True)
            prep=root.parent/'seali-owned-components-prepare.log'
            if prep.exists(): shutil.move(prep,root/'evidence/prepare.log')
            try:
                public=custody(root,repo,summary)
                print(json.dumps(public))
            except BaseException as error:
                failed=True
                print(json.dumps({'status':'CUSTODY_FAILED','error_type':type(error).__name__,
                    'source_sha':a.expected_source_sha,'runtime_tested':False,'publication_ready':False}))
        else:
            print(json.dumps({'status':'PREPARATION_FAILED_BEFORE_ROOT','source_sha':a.expected_source_sha}))
    raise SystemExit(1 if failed else 0)


if __name__=='__main__':
    def stop(signum,frame): raise InterruptedError('signal '+str(signum))
    signal.signal(signal.SIGTERM,stop);signal.signal(signal.SIGHUP,stop)
    main()

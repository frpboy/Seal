package com.junkfood.seal

import android.content.Context
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.junkfood.seal.util.VerifiedYtDlpUpdater
import com.junkfood.seal.util.YtDlpInstallResolution
import java.io.File
import org.junit.After
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Seeds the real on-device layout pre-baseline installs are in - an extracted
 * legacy yt-dlp binary with no dlpVersion pref - and proves the migration
 * paths at runtime: honest version resolution, pref repair only when the
 * bytes prove the bundle, and no destructive replacement during resolution.
 * Every mutation is restored afterward; other tests see the original state.
 */
@RunWith(AndroidJUnit4::class)
class YtDlpLegacyUpgradeEmulatorTest {

    private val context: Context
        get() = InstrumentationRegistry.getInstrumentation().targetContext
    private val prefs
        get() = context.getSharedPreferences("youtubedl-android", Context.MODE_PRIVATE)
    private val ytdlpDir
        get() = File(File(context.noBackupFilesDir, "youtubedl-android"), "ytdlp")
    private val binary
        get() = File(ytdlpDir, "yt-dlp")

    private var savedHadBinary = false
    private var savedBinary: ByteArray? = null
    private var savedVersion: String? = null
    private var savedVersionName: String? = null

    @Before
    fun captureState() {
        savedHadBinary = binary.isFile
        savedBinary = if (savedHadBinary) binary.readBytes() else null
        savedVersion = prefs.getString("dlpVersion", null)
        savedVersionName = prefs.getString("dlpVersionName", null)
    }

    @After
    fun restoreState() {
        if (savedHadBinary) {
            ytdlpDir.mkdirs()
            binary.writeBytes(savedBinary!!)
        } else {
            binary.delete()
        }
        val editor = prefs.edit()
        if (savedVersion == null) editor.remove("dlpVersion") else editor.putString("dlpVersion", savedVersion)
        if (savedVersionName == null) {
            editor.remove("dlpVersionName")
        } else {
            editor.putString("dlpVersionName", savedVersionName)
        }
        editor.commit()
    }

    private fun clearPref() {
        prefs.edit().remove("dlpVersion").remove("dlpVersionName").commit()
    }

    @Test
    fun legacyExtractedBinaryWithoutPrefResolvesUnknownLegacyAndKeepsBytes() {
        ytdlpDir.mkdirs()
        // Any non-bundled bytes exercise the same path; the hash comparison,
        // not the version string, drives the decision.
        val legacyBytes = "seali-legacy-yt-dlp-fixture-2024.09.27".toByteArray()
        binary.writeBytes(legacyBytes)
        clearPref()

        val resolution = VerifiedYtDlpUpdater.resolveInstall(context)

        assertEquals(YtDlpInstallResolution.State.UNKNOWN_LEGACY, resolution.state)
        assertNull(resolution.effectiveVersion)
        assertNull(resolution.prefRepairVersion)
        // No false baseline written and the existing binary is untouched.
        assertNull(prefs.getString("dlpVersion", null))
        assertTrue(binary.readBytes().contentEquals(legacyBytes))
    }

    @Test
    fun bundledBinaryWithoutPrefRepairsPrefToBundledVersion() {
        ytdlpDir.mkdirs()
        context.resources.openRawResource(R.raw.ytdlp).use { input ->
            binary.outputStream().use { output -> input.copyTo(output) }
        }
        clearPref()

        val resolution = VerifiedYtDlpUpdater.resolveInstall(context)

        assertEquals(YtDlpInstallResolution.State.BUNDLED, resolution.state)
        assertEquals(BuildConfig.BUNDLED_YTDLP_VERSION, resolution.effectiveVersion)
        assertEquals(BuildConfig.BUNDLED_YTDLP_VERSION, prefs.getString("dlpVersion", null))
    }

    @Test
    fun spoofedHighVersionMetadataDoesNotFreezeOrLaunder() {
        ytdlpDir.mkdirs()
        // A zipapp-shaped fixture CLAIMING a far-future version: self-asserted
        // metadata must not freeze updates or enter the verified pref.
        val fixture = File(context.cacheDir, "spoofed-zipapp-fixture")
        java.util.zip.ZipOutputStream(fixture.outputStream()).use { out ->
            out.putNextEntry(java.util.zip.ZipEntry("yt_dlp/version.py"))
            out.write("# Autogenerated\n\n__version__ = '2999.01.01'\n".toByteArray())
            out.closeEntry()
        }
        val fixtureBytes = fixture.readBytes()
        binary.writeBytes(fixtureBytes)
        fixture.delete()
        clearPref()

        val resolution = VerifiedYtDlpUpdater.resolveInstall(context)

        // Decision: still UNKNOWN_LEGACY - the claim is ignored, not trusted.
        assertEquals(YtDlpInstallResolution.State.UNKNOWN_LEGACY, resolution.state)
        assertNull(resolution.effectiveVersion)
        assertNull(resolution.prefRepairVersion)
        // The verified pref is NOT laundered with the self-asserted claim...
        assertNull(prefs.getString("dlpVersion", null))
        // ...the claim survives only as a clearly marked unverified hint...
        assertEquals(
            "self-reported 2999.01.01 (unverified)",
            prefs.getString("sealiYtdlpUnverifiedBinaryHint", null),
        )
        // ...and the binary itself is untouched by resolution.
        assertTrue(binary.readBytes().contentEquals(fixtureBytes))
    }

    @Test
    fun prefRecordedNewerBinaryIsNotDowngradedOrRepaired() {
        ytdlpDir.mkdirs()
        val foreignBytes = "seali-user-updated-yt-dlp-2999.01.01".toByteArray()
        binary.writeBytes(foreignBytes)
        prefs.edit()
            .putString("dlpVersion", "2999.01.01")
            .putString("dlpVersionName", "yt-dlp 2999.01.01")
            .commit()

        val resolution = VerifiedYtDlpUpdater.resolveInstall(context)

        assertEquals(YtDlpInstallResolution.State.PREF_RECORDED, resolution.state)
        assertEquals("2999.01.01", resolution.effectiveVersion)
        assertNull(resolution.prefRepairVersion)
        assertTrue(binary.readBytes().contentEquals(foreignBytes))
        assertEquals("2999.01.01", prefs.getString("dlpVersion", null))
    }
}
